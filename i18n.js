  function formatDelay(ms, lang) {
    const nf = new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en', { maximumFractionDigits: 1 });
    const min = ms / 60e3;
    const day = ms / 864e5;
    const u = lang === 'fa'
      ? { m: 'دقیقه', d: 'روز', mo: 'ماه', y: 'سال' }
      : { m: 'min', d: 'd', mo: 'mo', y: 'y' };
    const sep = lang === 'fa' ? ' ' : '';
    if (min < 60) return `${nf.format(Math.max(1, Math.round(min)))}${sep || ' '}${u.m}`;
    if (day < 1) return `${nf.format(Math.round(min / 60))}${lang === 'fa' ? ' ساعت' : 'h'}`;
    if (day < 31) return `${nf.format(Math.round(day))}${sep}${u.d}`;
    if (day < 365) return `${nf.format(Math.round(day / 30))}${sep}${u.mo}`;
    return `${nf.format(Math.round((day / 365) * 10) / 10)}${sep}${u.y}`;
  }

